import AppKit
import CryptoKit
import ImageIO
import UniformTypeIdentifiers
import Vision

/// One format of one pasteboard item, byte for byte as the source app wrote it.
struct ClipRepresentation: Codable, Equatable, Sendable {
    let type: String
    let data: Data
}

/// A complete copy of the pasteboard: every item, in every format.
struct ClipPayload: Codable, Equatable, Sendable {
    /// Clips above this size drop their largest formats, keeping plain text if possible.
    static let maxBytes = 200 * 1024 * 1024

    /// Markers from nspasteboard.org and password managers asking not to be recorded.
    static let ignoredTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",
        "de.petermaurer.TransientPasteboardType",
    ]

    /// Set by macOS on clips that arrived through Universal Clipboard.
    static let otherDeviceType = NSPasteboard.PasteboardType("com.apple.is-remote-clipboard")

    private static let plainTextType = NSPasteboard.PasteboardType.string.rawValue
    private static let fileURLType = NSPasteboard.PasteboardType.fileURL.rawValue

    var items: [[ClipRepresentation]]

    init(items: [[ClipRepresentation]]) {
        self.items = items
    }

    /// Returns nil when the pasteboard is empty, or asks not to be recorded and that isn't overridden.
    init?(pasteboard: NSPasteboard, includeSensitive: Bool = false) {
        let types = pasteboard.types ?? []
        guard includeSensitive || !types.contains(where: { Self.ignoredTypes.contains($0.rawValue) }) else { return nil }

        var items = (pasteboard.pasteboardItems ?? []).map { item in
            item.types.compactMap { type in
                item.data(forType: type).map { ClipRepresentation(type: type.rawValue, data: $0) }
            }
        }
        items.removeAll(where: \.isEmpty)
        guard !items.isEmpty else { return nil }

        self.items = items
        trimToLimit()
    }

    func write(to pasteboard: NSPasteboard) {
        pasteboard.clearContents()
        pasteboard.writeObjects(items.map { representations in
            let item = NSPasteboardItem()
            for representation in representations {
                item.setData(representation.data, forType: .init(representation.type))
            }
            return item
        })
    }

    // MARK: - Reading

    var allRepresentations: [ClipRepresentation] { items.flatMap { $0 } }

    var byteCount: Int { allRepresentations.reduce(0) { $0 + $1.data.count } }

    var plainText: String? {
        let lines = items.compactMap { item in
            item.first { $0.type == Self.plainTextType }
                .flatMap { String(data: $0.data, encoding: .utf8) }
        }
        return lines.isEmpty ? nil : lines.joined(separator: "\n")
    }

    var fileURLs: [URL] {
        items.compactMap { item in
            item.first { $0.type == Self.fileURLType }
                .flatMap { URL(dataRepresentation: $0.data, relativeTo: nil) }
        }
    }

    var contentHash: String {
        var hasher = SHA256()
        for item in items {
            for representation in item {
                hasher.update(data: Data(representation.type.utf8))
                hasher.update(data: representation.data)
            }
        }
        return hasher.finalize().map { String(format: "%02x", $0) }.joined()
    }

    /// How the clip is listed. Nil for clips with nothing worth keeping, like blank text.
    var kind: ClipKind? {
        let urls = fileURLs
        if !urls.isEmpty { return .files(urls.map(\.lastPathComponent)) }

        if let text = plainText {
            let trimmed = text.trimmingCharacters(in: .whitespacesAndNewlines)
            if !trimmed.isEmpty { return .text(String(trimmed.prefix(ClipKind.maxStoredText))) }
            if imageRepresentation == nil { return nil }
        }

        if imageRepresentation != nil { return .image }

        let description = allRepresentations.lazy
            .compactMap { UTType($0.type)?.localizedDescription }
            .first
        return .other(description ?? "Clip")
    }

    private var imageRepresentation: ClipRepresentation? {
        allRepresentations.first { UTType($0.type)?.conforms(to: .image) == true }
    }

    private var imageSource: CGImageSource? {
        if let image = imageRepresentation {
            return CGImageSourceCreateWithData(image.data as CFData, nil)
        }
        if let url = fileURLs.first(where: { UTType(filenameExtension: $0.pathExtension)?.conforms(to: .image) == true }) {
            return CGImageSourceCreateWithURL(url as CFURL, nil)
        }
        return nil
    }

    /// Images without any text of their own get searchable text from text recognition.
    var needsTextRecognition: Bool {
        let hasText = plainText?.contains { !$0.isWhitespace } == true
        return !hasText && imageSource != nil
    }

    /// Reads the text in the image, on this Mac. Slow, so call it off the main thread.
    func recognizedText(maxPixelSize: Int = 3000) -> String? {
        guard let source = imageSource,
              let image = CGImageSourceCreateThumbnailAtIndex(source, 0, [
                  kCGImageSourceCreateThumbnailFromImageAlways: true,
                  kCGImageSourceCreateThumbnailWithTransform: true,
                  kCGImageSourceThumbnailMaxPixelSize: maxPixelSize,
              ] as CFDictionary)
        else { return nil }

        let request = VNRecognizeTextRequest()
        request.recognitionLevel = .accurate
        request.automaticallyDetectsLanguage = true
        guard (try? VNImageRequestHandler(cgImage: image).perform([request])) != nil else { return nil }

        let lines = (request.results ?? []).compactMap { $0.topCandidates(1).first?.string }
        return lines.isEmpty ? nil : lines.joined(separator: "\n")
    }

    /// A small PNG for the list row. The original bytes stay in the payload.
    func makeThumbnail(maxPixelSize: Int = 256) -> Data? {
        guard let source = imageSource else { return nil }

        let options: [CFString: Any] = [
            kCGImageSourceCreateThumbnailFromImageAlways: true,
            kCGImageSourceCreateThumbnailWithTransform: true,
            kCGImageSourceThumbnailMaxPixelSize: maxPixelSize,
        ]
        guard let thumbnail = CGImageSourceCreateThumbnailAtIndex(source, 0, options as CFDictionary) else { return nil }

        let output = NSMutableData()
        guard let destination = CGImageDestinationCreateWithData(output, UTType.png.identifier as CFString, 1, nil) else { return nil }
        CGImageDestinationAddImage(destination, thumbnail, nil)
        guard CGImageDestinationFinalize(destination) else { return nil }
        return output as Data
    }

    // MARK: - Size limit

    private mutating func trimToLimit() {
        while byteCount > Self.maxBytes {
            let candidates = allRepresentations.filter { $0.type != Self.plainTextType }
            guard let largest = candidates.max(by: { $0.data.count < $1.data.count }) else { return }
            for index in items.indices {
                items[index].removeAll { $0 == largest }
            }
            items.removeAll(where: \.isEmpty)
        }
    }
}

enum ClipKind: Codable, Equatable, Sendable {
    /// Listing and search only need the start of a long text; the full text is in the payload.
    static let maxStoredText = 4096

    case text(String)
    case image
    case files([String])
    case other(String)
}
